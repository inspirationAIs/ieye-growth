export function getPeriodForAge(ageMonths: number): KDSTPeriod | undefined {
  return KDST_PERIODS.find(
    (p) => ageMonths >= p.ageRange[0] && ageMonths <= p.ageRange[1]
  ) ?? KDST_PERIODS.find(
    (p) => ageMonths < p.ageRange[0]
  ) ?? KDST_PERIODS[KDST_PERIODS.length - 1];
}

export function getMilestoneForAge(ageMonths: number): MilestoneInfo | undefined {
  // Find closest milestone
  return MILESTONE_DATA.reduce((closest, current) => {
    const closestDist = Math.abs(closest.ageRange[0] - ageMonths);
    const currentDist = Math.abs(current.ageRange[0] - ageMonths);
    return currentDist < closestDist ? current : closest;
  });
}
